-- 목록 순서 유지
-- 행을 고치면(체크 등) Postgres는 순서 없이 읽을 때 그 행을 뒤로 보낼 수 있다.
-- 넣은 순서대로 늘어나는 번호(seq)를 두고 앱은 이 순서로 읽는다.
-- 한 번에 여러 행을 넣을 때(장보기 완료, 샘플 채우기)도 보낸 순서대로 번호가 붙는다.

alter table public.items add column seq bigint generated by default as identity;
alter table public.shop_items add column seq bigint generated by default as identity;
alter table public.inbox_items add column seq bigint generated by default as identity;
alter table public.meal_entries add column seq bigint generated by default as identity;
alter table public.tasks add column seq bigint generated by default as identity;
